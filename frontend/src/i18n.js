const LANGS = { de, en };

export function localize(hass, key, params = {}) {
  const lang = (hass && hass.language && hass.language.split("-")[0]) || "en";
  const table = LANGS[lang] || en;
  let text = table[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function dayLabel(hass, date) {
  const lang = (hass && hass.language) || "de";
  return date.toLocaleDateString(lang, { weekday: "short", day: "numeric", month: "numeric" });
}
